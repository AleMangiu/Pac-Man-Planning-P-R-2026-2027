"""Generate every PDDL/RDDL file of the project from tools/maps.py.

  python3 tools/gen.py

Outputs
  classical/domain_strips.pddl          STRIPS compilation of the ADL domain
  classical/problems/adl/pXX.pddl       problems for classical/domain_adl.pddl
  classical/problems/strips/pXX.pddl    problems for classical/domain_strips.pddl
  numeric/problems/pXX.pddl             problems for numeric/domain.pddl
  rddl/instances/pXX.rddl               instances for rddl/domain.rddl
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from game import Game, cell_name  # noqa: E402
from maps import MAPS  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PILL_DURATION = 8   # numeric variant: steps of power given by a pill
LIVES = 3           # numeric variant: initial lives
RDDL_HORIZON = {"p01": 40, "p02": 50, "p03": 90, "p04": 110, "p05": 160}


def ph(p):
    return f"ph{p}"


def write(path, text):
    path = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


def wrap(facts, indent="    ", width=4):
    lines = []
    for i in range(0, len(facts), width):
        lines.append(indent + " ".join(facts[i:i + width]))
    return "\n".join(lines)


# --------------------------------------------------------------------------- #
# shared pieces
# --------------------------------------------------------------------------- #
def objects(g):
    cells = " ".join(cell_name(c) for c in g.cells)
    phases = " ".join(ph(p) for p in range(g.nphases))
    ghosts = " ".join(g.ghosts)
    out = f"    {cells} - cell\n    {phases} - phase"
    if ghosts:
        out += f"\n    {ghosts} - ghost"
    return out


def common_init(g):
    f = [f"(at {cell_name(g.start)})", f"(now {ph(0)})"]
    f += [f"(adj {cell_name(a)} {cell_name(b)})" for a in g.cells for b in g.adj[a]]
    f += [f"(next {ph(p)} {ph(g.nxt(p))})" for p in range(g.nphases)]
    f += [f"(dot {cell_name(c)})" for c in sorted(g.dots)]
    f += [f"(pill {cell_name(c)})" for c in sorted(g.pills)]
    f += [f"(alive {x})" for x in g.ghosts]
    for frm, to in g.transitions():
        for p in range(g.nphases):
            for x in g.threats(frm, to, p):
                f.append(f"(threat {x} {cell_name(frm)} {cell_name(to)} {ph(p)})")
    return f


def header(g, name, domain, comment):
    grid = "\n".join(";;   " + r for r in g.grid)
    return (f";; {name}: {comment}\n;; {g.stats()}\n{grid}\n"
            f"(define (problem pacman-{name})\n  (:domain {domain})\n")


# --------------------------------------------------------------------------- #
# classical ADL problems
# --------------------------------------------------------------------------- #
def adl_problem(name, g, spec):
    init = common_init(g)
    return (header(g, name, "pacman-adl", spec["note"]) +
            f"  (:objects\n{objects(g)})\n"
            f"  (:init\n{wrap(init)})\n"
            "  (:goal (forall (?c - cell) (not (dot ?c)))))\n")


# --------------------------------------------------------------------------- #
# STRIPS compilation
# --------------------------------------------------------------------------- #
CONTENT = {
    # name: (preconditions on ?to, effects)
    "dot": ("(dot ?to)", "(not (dot ?to)) (no-dot ?to)"),
    "pill": ("(pill ?to)", "(not (pill ?to)) (no-pill ?to) (powered)"),
    "empty": ("(no-dot ?to) (no-pill ?to)", ""),
}
GHOST = {
    # name: (extra parameter, preconditions, effects) ; {f}/{t} = from/to variables
    "free": ("", "(free {f} {t} ?p)", ""),
    "dead": (" ?g - ghost", "(threat ?g {f} {t} ?p) (dead ?g)", ""),
    "eat": (" ?g - ghost", "(threat ?g {f} {t} ?p) (alive ?g) (powered)",
            "(not (alive ?g)) (dead ?g)"),
}


def strips_domain():
    acts = []
    for gname, (gpar, gpre, geff) in GHOST.items():
        for cname, (cpre, ceff) in CONTENT.items():
            acts.append(f"""  (:action move-{cname}-{gname}
    :parameters (?from ?to - cell ?p ?q - phase{gpar})
    :precondition (and (at ?from) (adj ?from ?to) (now ?p) (next ?p ?q)
                       {cpre} {gpre.format(f='?from', t='?to')})
    :effect (and (not (at ?from)) (at ?to) (not (now ?p)) (now ?q)
                 {ceff} {geff}))
""")
        acts.append(f"""  (:action wait-{gname}
    :parameters (?c - cell ?p ?q - phase{gpar})
    :precondition (and (at ?c) (now ?p) (next ?p ?q) {gpre.format(f='?c', t='?c')})
    :effect (and (not (now ?p)) (now ?q) {geff}))
""")
    return f""";; Simplified Pac-Man - STRIPS compilation of domain_adl.pddl
;; (generated by tools/gen.py - do not edit by hand)
;;
;; Needed to use heuristics that do not support conditional effects or the
;; axioms that Fast Downward introduces for quantified/negated conditions
;; (e.g. LM-cut). How the ADL constructs are compiled away:
;;  * conditional effects on the target cell (dot / pill / nothing)
;;      -> one action per case: move-dot-*, move-pill-*, move-empty-*
;;  * forall over ghosts in precondition and effects
;;      -> one action per case: no threat (free, precomputed static fact),
;;         threatening ghost already dead, threatening ghost eaten (powered).
;;         Valid because the generator checks that at most one ghost
;;         threatens any single step.
;;  * negative conditions (not (dot ?c)) / goal forall
;;      -> complementary positive predicates no-dot / no-pill / dead, exactly
;;         as in the positive normal form construction seen in class; the
;;         goal lists (no-dot c) for every dot cell.
;; 2 conditional effects x 3 ghost cases = 9 move actions + 3 wait actions
;; instead of 2 schemas.

(define (domain pacman-strips)
  (:requirements :strips :typing)
  (:types cell ghost phase)
  (:predicates
    (at ?c - cell) (adj ?c1 ?c2 - cell)
    (dot ?c - cell) (no-dot ?c - cell) (pill ?c - cell) (no-pill ?c - cell)
    (powered) (alive ?g - ghost) (dead ?g - ghost)
    (now ?p - phase) (next ?p1 ?p2 - phase)
    (threat ?g - ghost ?from ?to - cell ?p - phase)
    (free ?from ?to - cell ?p - phase))

{"".join(acts)})
"""


def strips_problem(name, g, spec):
    init = common_init(g)
    init += [f"(no-dot {cell_name(c)})" for c in g.cells if c not in g.dots]
    init += [f"(no-pill {cell_name(c)})" for c in g.cells if c not in g.pills]
    for frm, to in g.transitions():
        for p in range(g.nphases):
            if not g.threats(frm, to, p):
                init.append(f"(free {cell_name(frm)} {cell_name(to)} {ph(p)})")
    goal = [f"(no-dot {cell_name(c)})" for c in sorted(g.dots)]
    return (header(g, name, "pacman-strips", spec["note"]) +
            f"  (:objects\n{objects(g)})\n"
            f"  (:init\n{wrap(init)})\n"
            f"  (:goal (and\n{wrap(goal, '    ', 6)})))\n")


# --------------------------------------------------------------------------- #
# numeric problems
# --------------------------------------------------------------------------- #
def numeric_problem(name, g, spec):
    init = common_init(g)
    init += [f"(= (power) 0)", f"(= (pill-duration) {PILL_DURATION})",
             f"(= (lives) {LIVES})", f"(= (dots-left) {len(g.dots)})",
             "(= (steps) 0)", "(= (hits) 0)"]
    return (header(g, name, "pacman-numeric", spec["note"]) +
            f"  (:objects\n{objects(g)})\n"
            f"  (:init\n{wrap(init)})\n"
            "  (:goal (<= (dots-left) 0))\n"
            "  (:metric minimize (+ (steps) (* 10 (hits)))))\n")


# --------------------------------------------------------------------------- #
# RDDL instances (domain in rddl/domain.rddl)
# --------------------------------------------------------------------------- #
def rddl_instance(name, g, spec):
    cells = ", ".join(cell_name(c) for c in g.cells)
    ghosts = ", ".join(g.ghosts)
    nf = [f"ADJ({cell_name(a)}, {cell_name(b)}) = true;" for a in g.cells for b in g.adj[a]]
    # each ghost's patrol: index st_i -> cell, and cyclic successor of the index
    for k, x in enumerate(g.ghosts):
        for i, c in enumerate(g.cycles[k]):
            nf.append(f"ROUTE({x}, st{i}, {cell_name(c)}) = true;")
    steps = max(len(c) for c in g.cycles)
    st = ", ".join(f"st{i}" for i in range(steps))
    nf += [f"STEP-NEXT({x}, st{i}, st{(i + 1) % len(g.cycles[k])}) = true;"
           for k, x in enumerate(g.ghosts) for i in range(len(g.cycles[k]))]
    init = [f"pacman-at({cell_name(g.start)}) = true;"]
    init += [f"dot({cell_name(c)}) = true;" for c in sorted(g.dots)]
    init += [f"pill({cell_name(c)}) = true;" for c in sorted(g.pills)]
    init += [f"ghost-step({x}, st0) = true;" for x in g.ghosts]
    nl = "\n        "
    return f"""// {name}: {spec['note']}  {g.stats()}
{chr(10).join('//   ' + r for r in g.grid)}
non-fluents nf_pacman_{name} {{
    domain = pacman_mdp;
    objects {{
        cell : {{{cells}}};
        ghost : {{{ghosts}}};
        step : {{{st}}};
    }};
    non-fluents {{
        {nl.join(nf)}
    }};
}}

instance pacman_{name} {{
    domain = pacman_mdp;
    non-fluents = nf_pacman_{name};
    init-state {{
        {nl.join(init)}
    }};
    max-nondef-actions = 1;
    horizon = {RDDL_HORIZON[name]};
    discount = 1.0;
}}
"""


def main():
    write("classical/domain_strips.pddl", strips_domain())
    for name, spec in MAPS.items():
        g = Game(spec, name)
        g.check_single_threat()
        write(f"classical/problems/adl/{name}.pddl", adl_problem(name, g, spec))
        write(f"classical/problems/strips/{name}.pddl", strips_problem(name, g, spec))
        write(f"numeric/problems/{name}.pddl", numeric_problem(name, g, spec))
        write(f"rddl/instances/{name}.rddl", rddl_instance(name, g, spec))
        print(name, g.stats())


if __name__ == "__main__":
    main()
